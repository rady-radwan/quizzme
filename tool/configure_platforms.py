"""Idempotently applies Quiz me's platform configuration to the folders
generated by `flutter create`:

Android
  * app name "Quiz me"
  * POST_NOTIFICATIONS / RECEIVE_BOOT_COMPLETED permissions and the receivers
    required by flutter_local_notifications for scheduled reminders
  * <queries> entry so text-to-speech engines are visible on Android 11+
  * core library desugaring (required by flutter_local_notifications)
  * release signing from android/key.properties when present (never committed),
    otherwise the debug key so `flutter build apk --release` still works
iOS / Windows
  * display name "Quiz me"

Safe to run any number of times. Run from the repository root:
    python3 tool/configure_platforms.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MARK = 'quiz-me-config'


def patch_manifest():
    f = ROOT / 'android/app/src/main/AndroidManifest.xml'
    if not f.exists():
        print('skip: no AndroidManifest.xml')
        return
    s = f.read_text()
    s = re.sub(r'android:label="[^"]*"', 'android:label="Quiz me"', s, count=1)
    if 'android:roundIcon' not in s:
        s = s.replace('android:icon="@mipmap/ic_launcher"',
                      'android:icon="@mipmap/ic_launcher"\n        android:roundIcon="@mipmap/ic_launcher_round"', 1)
    if 'android.permission.POST_NOTIFICATIONS' not in s:
        perms = ('    <uses-permission android:name="android.permission.POST_NOTIFICATIONS"/>\n'
                 '    <uses-permission android:name="android.permission.RECEIVE_BOOT_COMPLETED"/>\n')
        s = re.sub(r'\n(\s*)<application', lambda m: '\n' + perms + m.group(1) + '<application', s, count=1)
    if 'ScheduledNotificationReceiver' not in s:
        receivers = '''
        <!-- quiz-me-config: flutter_local_notifications -->
        <receiver android:exported="false" android:name="com.dexterous.flutterlocalnotifications.ScheduledNotificationReceiver" />
        <receiver android:exported="false" android:name="com.dexterous.flutterlocalnotifications.ScheduledNotificationBootReceiver">
            <intent-filter>
                <action android:name="android.intent.action.BOOT_COMPLETED"/>
                <action android:name="android.intent.action.MY_PACKAGE_REPLACED"/>
                <action android:name="android.intent.action.QUICKBOOT_POWERON" />
                <action android:name="com.htc.intent.action.QUICKBOOT_POWERON"/>
            </intent-filter>
        </receiver>
'''
        s = s.replace('</application>', receivers + '    </application>', 1)
    if 'android.intent.action.TTS_SERVICE' not in s:
        tts = ('        <intent>\n            <action android:name="android.intent.action.TTS_SERVICE" />\n'
               '        </intent>\n')
        if '<queries>' in s:
            s = s.replace('<queries>', '<queries>\n' + tts, 1)
        else:
            s = s.replace('</manifest>', '    <queries>\n' + tts + '    </queries>\n</manifest>', 1)
    f.write_text(s)
    print('patched', f.relative_to(ROOT))


SIGNING_KTS_TOP = '''// quiz-me-config: optional release signing (android/key.properties is never committed)
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
}

'''

SIGNING_KTS_BLOCK = '''    signingConfigs {
        create("release") {
            if (keystorePropertiesFile.exists()) {
                keyAlias = keystoreProperties["keyAlias"] as String
                keyPassword = keystoreProperties["keyPassword"] as String
                storeFile = file(keystoreProperties["storeFile"] as String)
                storePassword = keystoreProperties["storePassword"] as String
            }
        }
    }

'''


def patch_gradle_kts(f):
    s = f.read_text()
    # Older versions of this script used fully qualified java.* names, which the
    # Kotlin DSL cannot resolve; switch to imports.
    s = s.replace('java.util.Properties()', 'Properties()')
    s = s.replace('java.io.FileInputStream(', 'FileInputStream(')
    for imp in ('import java.io.FileInputStream', 'import java.util.Properties'):
        if imp not in s:
            s = imp + '\n' + s
    if MARK not in s:
        s = re.sub(r'(\nandroid \{)', '\n' + SIGNING_KTS_TOP.rstrip('\n') + r'\n\1', s, count=1)
    if 'isCoreLibraryDesugaringEnabled' not in s:
        s = re.sub(r'compileOptions \{', 'compileOptions {\n        isCoreLibraryDesugaringEnabled = true', s, count=1)
    if 'signingConfigs {' not in s:
        s = re.sub(r'(\n    buildTypes \{)', '\n' + SIGNING_KTS_BLOCK.rstrip('\n') + r'\n\1', s, count=1)
    s = s.replace('signingConfig = signingConfigs.getByName("debug")',
                  'signingConfig = if (keystorePropertiesFile.exists()) signingConfigs.getByName("release") '
                  'else signingConfigs.getByName("debug")')
    if 'desugar_jdk_libs' not in s:
        s = s.rstrip('\n') + '\n\ndependencies {\n    coreLibraryDesugaring("com.android.tools:desugar_jdk_libs:2.1.4")\n}\n'
    f.write_text(s)
    print('patched', f.relative_to(ROOT))


def patch_gradle_groovy(f):
    s = f.read_text()
    if 'coreLibraryDesugaringEnabled' not in s:
        s = re.sub(r'compileOptions \{', 'compileOptions {\n        coreLibraryDesugaringEnabled true', s, count=1)
    if 'desugar_jdk_libs' not in s:
        s = s.rstrip('\n') + "\n\ndependencies {\n    coreLibraryDesugaring 'com.android.tools:desugar_jdk_libs:2.1.4'\n}\n"
    f.write_text(s)
    print('patched', f.relative_to(ROOT))


def patch_ios():
    f = ROOT / 'ios/Runner/Info.plist'
    if not f.exists():
        return
    s = f.read_text()
    s = re.sub(r'(<key>CFBundleDisplayName</key>\s*<string>)[^<]*(</string>)', r'\1Quiz me\2', s)
    f.write_text(s)
    print('patched', f.relative_to(ROOT))


def patch_windows():
    win = ROOT / 'windows'
    if not win.exists():
        return
    main_cpp = win / 'runner/main.cpp'
    if main_cpp.exists():
        s = main_cpp.read_text()
        s = s.replace('window.Create(L"quiz_me"', 'window.Create(L"Quiz me"')
        s = s.replace('Win32Window::Size size(1280, 720);', 'Win32Window::Size size(1280, 860);')
        main_cpp.write_text(s)
    fw = win / 'runner/flutter_window.cpp'
    if fw.exists():
        s = fw.read_text()
        if 'WM_GETMINMAXINFO' not in s and 'case WM_FONTCHANGE:' in s:
            s = s.replace('    case WM_FONTCHANGE:', """    case WM_GETMINMAXINFO: {
      // quiz-me-config: keep the window large enough for the layout.
      const double scale = FlutterDesktopGetDpiForMonitor(
          MonitorFromWindow(hwnd, MONITOR_DEFAULTTONEAREST)) / 96.0;
      auto* info = reinterpret_cast<MINMAXINFO*>(lparam);
      info->ptMinTrackSize.x = static_cast<LONG>(760 * scale);
      info->ptMinTrackSize.y = static_cast<LONG>(560 * scale);
      return 0;
    }
    case WM_FONTCHANGE:""", 1)
        fw.write_text(s)
    cm = win / 'CMakeLists.txt'
    if cm.exists():
        s = cm.read_text()
        s = s.replace('set(BINARY_NAME "quiz_me")', 'set(BINARY_NAME "QuizMe")')
        cm.write_text(s)
    rc = win / 'runner/Runner.rc'
    if rc.exists():
        s = rc.read_text()
        s = s.replace('VALUE "FileDescription", "quiz_me"', 'VALUE "FileDescription", "Quiz me"')
        s = s.replace('VALUE "ProductName", "quiz_me"', 'VALUE "ProductName", "Quiz me"')
        s = s.replace('VALUE "OriginalFilename", "quiz_me.exe"', 'VALUE "OriginalFilename", "QuizMe.exe"')
        s = s.replace('VALUE "CompanyName", "com.radyradwan"', 'VALUE "CompanyName", "Rady Radwan"')
        rc.write_text(s)
    print('patched windows runner')


def copy_branding():
    """Copies the Quiz me launcher icons (generated from the logo) into the
    platform folders, replacing the default Flutter icons."""
    import shutil
    src = ROOT / 'tool/branding/android/res'
    dst = ROOT / 'android/app/src/main/res'
    if src.exists() and dst.exists():
        for f in src.rglob('*'):
            if f.is_file():
                target = dst / f.relative_to(src)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(f, target)
        print('copied Android launcher icons')
    ico = ROOT / 'tool/branding/app_icon.ico'
    win = ROOT / 'windows/runner/resources/app_icon.ico'
    if ico.exists() and win.parent.exists():
        shutil.copyfile(ico, win)
        print('copied Windows icon')


def main():
    copy_branding()
    patch_manifest()
    kts = ROOT / 'android/app/build.gradle.kts'
    groovy = ROOT / 'android/app/build.gradle'
    if kts.exists():
        patch_gradle_kts(kts)
    elif groovy.exists():
        patch_gradle_groovy(groovy)
    else:
        print('skip: no android app build file')
    patch_ios()
    patch_windows()
    return 0


if __name__ == '__main__':
    sys.exit(main())
